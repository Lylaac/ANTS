using Godot;

public partial class GroundMesh : MeshInstance2D
{
    StaticBody2D staticBody2D = new StaticBody2D();
	ConcavePolygonShape2D shape = new ConcavePolygonShape2D();
	CollisionShape2D collisionShape = new CollisionShape2D();

	// Called when the node enters the scene tree for the first time.
	public override void _Ready()
    {
        MarchingSquares.generateField(); //initialise our marching squares
        MarchingSquares.generateVertexes();
        generateMesh();
        collisionShape.SetShape(shape); // for collisions we need a collision shape and a static body2d
		staticBody2D.AddChild(collisionShape);
        AddChild(staticBody2D);

    }

	// Called every frame. 'delta' is the elapsed time since the previous frame.
	public override void _Process(double delta)
    {

        if (Input.IsActionPressed("debug_add_terrain"))
        {
            MarchingSquares.edit(GetGlobalMousePosition(), false);
            MarchingSquares.edited = true;
        }
        else if (Input.IsActionPressed("debug_remove_terrain"))
        {
            MarchingSquares.edit(GetGlobalMousePosition(), true);
            MarchingSquares.edited = true;
        }
        if (MarchingSquares.edited) // if the marching squares class has been edited since we last updated our version of it, then we need to update the version of the mesh here
        {
            generateMesh();
            MarchingSquares.edited = false;
        }
    }

    private void generateMesh()
    {
        var immMesh = new ImmediateMesh(); // immediate meshes are fast to create
        Color col = new Color(0.5f, 0.2f, 0.1f); // create a brownish colour, we could change this for each vertex but for now i just have one colour for the entire mesh
        
        immMesh.SurfaceBegin(Mesh.PrimitiveType.Triangles); // mkae it a mesh of triangles
        immMesh.SurfaceSetColor(col); // set the colour
        for (int count = 0; count < MarchingSquares.verts.Count; count++) // iterate through the vertexes generated by the marching squares algorithm and add them to our mesh
        {
            immMesh.SurfaceAddVertex2D(MarchingSquares.verts[count]);
        }
        immMesh.SurfaceEnd(); // when we have finished adding things we end the surface
        SetMesh(immMesh); 
        Vector2[] vertices = MarchingSquares.edgeVerts.ToArray(); // this is for collision, instead of a concave polygon shape being a collection of triangles like a mesh, it is simply a collection of collision lines, so we use the edge verticies 
        shape.SetSegments(vertices);
        
    }
}
